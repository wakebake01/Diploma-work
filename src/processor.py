import re

def clean_text(text):
    """
    Тексті қоқыстан тазарту функциясы (Функция очистки текста).
    """
    if not text or not isinstance(text, str):
        return ""

    # 1. Ссылкалар мен хештегтерді жою (Удаление ссылок и тегов)
    text = re.sub(r'http\S+|www\S+|@\w+|#\w+', '', text)
    
    # 2. Тек әріптерді қалдыру (Оставляем только буквы казахского, русского и латинского алфавита)
    # Добавлены специфичные казахские буквы: ә, ғ, қ, ң, ө, ұ, ү, һ, і
    text = re.sub(r'[^a-zA-Zа-яА-ЯәғқңөұүһіӘҒҚҢӨҰҮҺІ\s]', '', text)
    
    # 3. Артық бос орындарды жою (Удаление лишних пробелов)
    text = text.strip().lower()
    
    return text
